#!/bin/bash
# Builds the Raiden OS .deb packages from packages/*/ into OUTDIR.
#
#   build-packages.sh OUTDIR
#
# Each package directory holds DEBIAN/ (control + maintainer scripts) and
# root/ (files to install). Placeholders like @DISTRO_NAME@ are filled from
# build.conf; generated artwork and vendored third-party files are added here.
# OUTDIR also gets Heroic's .deb and update-installed-system.sh (with the apt
# keys it needs), so the folder can update a system installed from an older ISO.
set -Eeuo pipefail

SRC_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
. "$SRC_DIR/build.conf"
. "$SRC_DIR/scripts/lib.sh"

OUT="${1:?usage: build-packages.sh OUTDIR}"
VERSION="${DISTRO_VERSION}+$(date -u +%Y%m%d.%H%M)"
STAGE="$(mktemp -d /var/tmp/raiden-pkg.XXXXXX)"
trap 'rm -rf "$STAGE"' EXIT

rm -rf "$OUT"
mkdir -p "$OUT"
bash "$SRC_DIR/scripts/fetch-vendor.sh" >/dev/null

log "Generating artwork"
bash "$SRC_DIR/artwork/make-assets.sh" "$STAGE/assets" >/dev/null
A="$STAGE/assets"

joined_list() { # file -> "a, b, c" (alternatives "x | y" are kept as written)
  sed -e 's/#.*//' -e 's/[[:space:]]\+$//' -e '/^[[:space:]]*$/d' "$1" | paste -sd, - | sed 's/,/, /g'
}

substitute() { # replace @PLACEHOLDERS@ in every text file of a staged package
  local dir="$1"
  # DISTRO_SHORT_NAME: the first word of the name, e.g. for the default layout
  export R_DISTRO_NAME="$DISTRO_NAME" R_DISTRO_SHORT_NAME="${DISTRO_NAME%% *}" \
         R_DISTRO_ID="$DISTRO_ID" R_DISTRO_VERSION="$DISTRO_VERSION" \
         R_DISTRO_HOME_URL="$DISTRO_HOME_URL" R_UBUNTU_SUITE="$UBUNTU_SUITE" \
         R_UBUNTU_VERSION="$UBUNTU_VERSION" R_KERNEL_FLAVOUR="$KERNEL_FLAVOUR" \
         R_NVIDIA_BRANCH="$NVIDIA_BRANCH" R_VERSION="$VERSION" \
         R_DESKTOP_DEPENDS="$(joined_list "$SRC_DIR/config/packages/desktop-depends.list")" \
         R_DESKTOP_RECOMMENDS="$(joined_list "$SRC_DIR/config/packages/desktop-recommends.list")" \
         R_LIVE_DEPENDS="$(joined_list "$SRC_DIR/config/packages/live-depends.list")"
  grep -rlI '@[A-Z_]*@' "$dir" 2>/dev/null | python3 -c '
import os, sys
keys = ["DISTRO_NAME", "DISTRO_SHORT_NAME", "DISTRO_ID", "DISTRO_VERSION", "DISTRO_HOME_URL", "UBUNTU_SUITE",
        "UBUNTU_VERSION", "KERNEL_FLAVOUR", "NVIDIA_BRANCH", "VERSION", "DESKTOP_DEPENDS",
        "DESKTOP_RECOMMENDS", "LIVE_DEPENDS"]
for path in sys.stdin.read().splitlines():
    text = open(path, encoding="utf-8").read()
    new = text
    for k in keys:
        new = new.replace("@" + k + "@", os.environ["R_" + k])
    if new != text:
        open(path, "w", encoding="utf-8").write(new)
'
}

fix_permissions() {
  local d="$1"
  find "$d" -type d -exec chmod 755 {} +
  find "$d" -type f -exec chmod 644 {} +
  for x in usr/bin usr/libexec usr/share/initramfs-tools/scripts usr/lib/NetworkManager/dispatcher.d; do
    [ -d "$d/$x" ] && find "$d/$x" -type f -exec chmod 755 {} +
  done
  for s in preinst postinst prerm postrm config; do
    [ -f "$d/DEBIAN/$s" ] && chmod 755 "$d/DEBIAN/$s"
  done
  [ -d "$d/etc/netplan" ] && find "$d/etc/netplan" -type f -exec chmod 600 {} +
  return 0
}

# ---------------------------------------------------------- per-package extras
extra_raiden_os_settings() {
  local d="$1" o="$1/usr/share/glib-2.0/schemas/90_raiden-os.gschema.override"
  install -Dm644 "$SRC_DIR/packages/raiden-os-settings/os-release.in" "$d/usr/lib/os-release"
  install -Dm644 "$SRC_DIR/vendor/keys/packages.mozilla.org.asc" "$d/usr/share/keyrings/packages.mozilla.org.asc"
  if [ "$EDITION" = public ]; then
    # Firefox is the browser until Chrome arrives (first start with internet);
    # pin it next to Chrome (taskbar and menu skip apps that are not installed)
    {
      echo "# Public edition: Firefox next to Chrome (generated by build-packages.sh)"
      echo "[org.gnome.shell]"
      grep '^favorite-apps=' "$o" | sed "s/'google-chrome.desktop'/&, 'firefox.desktop'/"
      echo
      echo "[org.gnome.shell.extensions.arcmenu]"
      grep '^pinned-apps=' "$o" | sed "s/{'id': 'google-chrome.desktop'}/&, {'id': 'firefox.desktop'}/"
    } > "$d/usr/share/glib-2.0/schemas/91_raiden-os-public.gschema.override"
  fi
}

extra_raiden_os_artwork() {
  local d="$1"
  mkdir -p "$d/usr/share/icons" "$d/usr/share/pixmaps" "$d/usr/share/backgrounds" \
           "$d/usr/share/gnome-background-properties" "$d/usr/share/plymouth/themes" \
           "$d/boot/grub/themes" "$d/usr/share/raiden-os"
  cp -a "$A/icons/hicolor" "$d/usr/share/icons/"
  cp -a "$A/pixmaps/." "$d/usr/share/pixmaps/"
  cp -a "$A/backgrounds/$DISTRO_ID" "$d/usr/share/backgrounds/"
  cp -a "$A/gnome-background-properties/." "$d/usr/share/gnome-background-properties/"
  cp -a "$A/plymouth/$DISTRO_ID" "$d/usr/share/plymouth/themes/"
  cp -a "$A/grub/$DISTRO_ID" "$d/boot/grub/themes/"
  cp -a "$A/fastfetch" "$d/usr/share/raiden-os/"

  # Login screen background (Ubuntu's GDM option), linked into the greeter's
  # settings like Debian's /etc/gdm3/greeter.dconf-defaults. Appearance ->
  # Characters rewrites the /etc file through a polkit-protected helper.
  local login_bg=""
  local C="$A/characters"
  if [ -d "$C" ]; then
    local j id
    install -d "$d/usr/share/backgrounds/$DISTRO_ID/characters" "$d/usr/share/raiden-os/characters"
    for j in "$C"/*.json; do
      id="$(basename "$j" .json)"
      local pic
      for pic in "$id" "$id-ultrawide" "$id-login" "$id-login-ultrawide"; do
        if [ -f "$C/$pic.jpg" ]; then
          install -m644 "$C/$pic.jpg" "$d/usr/share/backgrounds/$DISTRO_ID/characters/"
        fi
      done
      install -m644 "$j" "$C/$id-preview.jpg" "$C/$id-avatar.png" "$d/usr/share/raiden-os/characters/"
    done
    install -m644 "$C/raiden-os-characters.xml" "$d/usr/share/gnome-background-properties/"
    if [ -n "${DEFAULT_CHARACTER:-}" ] && [ -f "$C/$DEFAULT_CHARACTER.json" ]; then
      local wp="/usr/share/backgrounds/$DISTRO_ID/characters/$DEFAULT_CHARACTER.jpg" accent
      accent="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["accent"])' "$C/$DEFAULT_CHARACTER.json")"
      install -d "$d/usr/share/glib-2.0/schemas"
      cat > "$d/usr/share/glib-2.0/schemas/92_raiden-character-default.gschema.override" <<EOF
# Default character theme (build.conf DEFAULT_CHARACTER); Appearance ->
# Characters switches it per user.
[org.gnome.desktop.background]
picture-uri='file://$wp'
picture-uri-dark='file://$wp'
picture-options='zoom'

[org.gnome.desktop.screensaver]
picture-uri='file://$wp'

[org.gnome.desktop.interface]
accent-color='$accent'
EOF
      login_bg="$(python3 -c 'import json,sys; m=json.load(open(sys.argv[1])); print(m.get("login") or m["wallpaper"])' "$C/$DEFAULT_CHARACTER.json")"
    fi
  fi
  install -d "$d/etc/gdm3" "$d/usr/share/gdm/dconf"
  {
    echo "# Raiden OS login screen background. Appearance -> Characters rewrites"
    echo "# this file through /usr/libexec/raiden-appearance/set-login-background."
    echo "[com/ubuntu/login-screen]"
    if [ -n "$login_bg" ]; then
      echo "background-picture-uri='file://$login_bg'"
      echo "background-size='cover'"
      echo "background-repeat='no-repeat'"
      echo "background-color='#05030a'"
    fi
  } > "$d/etc/gdm3/raiden-login-background"
  ln -s /etc/gdm3/raiden-login-background "$d/usr/share/gdm/dconf/96-raiden-login-background"
}

extra_raiden_gnome_extensions() {
  local d="$1" zip uuid tmp schema
  mkdir -p "$d/usr/share/gnome-shell/extensions" "$d/usr/share/glib-2.0/schemas"
  for zip in "$SRC_DIR"/vendor/extensions/*.zip; do
    tmp="$(mktemp -d)"
    unzip -q "$zip" -d "$tmp"
    uuid="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["uuid"])' "$tmp/metadata.json")"
    # our fixes for upstream bugs; a patch that no longer applies stops the
    # build, so an extension update gets its patches reviewed
    local p
    for p in "$SRC_DIR/patches/extensions/$uuid"/*.patch; do
      [ -e "$p" ] || continue
      patch -s -p1 --no-backup-if-mismatch -d "$tmp" < "$p" ||
        die "could not apply $(basename "$p") to $uuid"
    done
    # global schemas, so gschema overrides apply; no per-extension compiled copy
    for schema in "$tmp"/schemas/*.gschema.xml; do
      [ -f "$schema" ] && install -m644 "$schema" "$d/usr/share/glib-2.0/schemas/"
    done
    rm -rf "$tmp/schemas"
    mv "$tmp" "$d/usr/share/gnome-shell/extensions/$uuid"
  done
  # Dash to Panel announces "has been updated!" whenever its stored version
  # differs from the installed one; preset it so first logins stay quiet.
  local dtp_ver
  dtp_ver="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["version"])' \
    "$d/usr/share/gnome-shell/extensions/dash-to-panel@jderose9.github.com/metadata.json")"
  printf '[org.gnome.shell.extensions.dash-to-panel]\nextension-version=%s\n' "$dtp_ver" \
    > "$d/usr/share/glib-2.0/schemas/91_raiden-gnome-extensions.gschema.override"
}

