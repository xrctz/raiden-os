extra_raiden_apps() {
  # The apps themselves are installed into /opt by apps-update (image build
  # and daily timer); the package carries their launchers and icons.
  local d="$1" s pp="$STAGE/protonplus"
  python3 "$SRC_DIR/scripts/antigravity-icons.py" \
    "$SRC_DIR"/vendor/apps/antigravity-[0-9]*-linux-x64.tar.gz \
    "$SRC_DIR"/vendor/apps/antigravity-ide-[0-9]*-linux-x64.tar.gz "$STAGE/antigravity-icons" >/dev/null
  for s in "$STAGE"/antigravity-icons/*; do
    install -d "$d/usr/share/icons/hicolor/$(basename "$s")/apps"
    install -m644 "$s"/*.png "$d/usr/share/icons/hicolor/$(basename "$s")/apps/"
  done
  install -d "$d/usr/bin"
  ln -s /opt/antigravity-ide/bin/antigravity-ide "$d/usr/bin/antigravity-ide"
  ln -s /opt/antigravity/antigravity "$d/usr/bin/antigravity"
  # ProtonPlus's own icon, for icon themes without one (Papirus has one).
  # The AppImage unpacks it, as an unprivileged user like apps-update does.
  chmod 711 "$STAGE"
  install -d -o nobody "$pp"
  install -m755 -o nobody "$SRC_DIR"/vendor/apps/protonplus-[0-9]*-x86_64.AppImage "$pp/app.AppImage"
  (cd "$pp" && setpriv --reuid=nobody --regid=nogroup --clear-groups --no-new-privs \
    ./app.AppImage --appimage-extract com.vysp3r.ProtonPlus.png >/dev/null 2>&1) ||
    die "cannot unpack the ProtonPlus icon"
  # (squashfs-root: the folder, or a link to it, with every AppImage runtime)
  install -Dm644 "$pp/squashfs-root/com.vysp3r.ProtonPlus.png" \
    "$d/usr/share/icons/hicolor/256x256/apps/com.vysp3r.ProtonPlus.png"
  # Outlook and Microsoft 365 use Papirus' icons; other icon themes find
  # them through these links
  install -d "$d/usr/share/icons/hicolor/scalable/apps"
  for s in ms-outlook microsoft-365; do
    ln -s "../../../Papirus/64x64/apps/$s.svg" "$d/usr/share/icons/hicolor/scalable/apps/$s.svg"
  done
}

