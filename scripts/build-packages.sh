}

# ------------------------------------------------------------------- build all
# every extra_<name> hook must belong to a package, or it would silently not run
for fn in $(declare -F | awk '$3 ~ /^extra_/ {print $3}'); do
  pkg="${fn#extra_}"
  [ -d "$SRC_DIR/packages/${pkg//_/-}" ] || die "$fn matches no package in packages/"
done
for pkgdir in "$SRC_DIR"/packages/*/; do
  name="$(basename "$pkgdir")"
  d="$STAGE/$name"
  mkdir -p "$d"
  [ -d "$pkgdir/root" ] && cp -a "$pkgdir/root/." "$d/"
  find "$d" -name __pycache__ -prune -exec rm -rf {} +   # left by local test runs
  cp -a "$pkgdir/DEBIAN" "$d/DEBIAN"
  fn="extra_${name//-/_}"
  if declare -F "$fn" >/dev/null; then "$fn" "$d"; fi
  substitute "$d"
  fix_permissions "$d"
  # every file under /etc is a configuration file
  if [ -d "$d/etc" ]; then
    (cd "$d" && find etc -type f | sed 's|^|/|' | sort) > "$d/DEBIAN/conffiles"
    [ -s "$d/DEBIAN/conffiles" ] || rm -f "$d/DEBIAN/conffiles"
  fi
  size="$(du -sk --exclude=DEBIAN "$d" | cut -f1)"
  sed -i "/^Installed-Size:/d" "$d/DEBIAN/control"
  echo "Installed-Size: $size" >> "$d/DEBIAN/control"
  if grep -q '@[A-Z_]*@' "$d/DEBIAN/control"; then die "unfilled placeholder in $name/DEBIAN/control"; fi
  dpkg-deb --root-owner-group -Zxz --build "$d" "$OUT/${name}_${VERSION}_all.deb" >/dev/null
  info "built ${name}_${VERSION}_all.deb ($(du -h "$OUT/${name}_${VERSION}_all.deb" | cut -f1))"
done

# ------------------------------------------ for updating installed systems
cp "$SRC_DIR"/vendor/apps/heroic_*_amd64.deb "$OUT/"
install -m755 "$SRC_DIR/scripts/update-installed-system.sh" "$OUT/"
install -Dm644 -t "$OUT/keys" "$SRC_DIR/vendor/keys/google-linux-signing-key.asc" \
  "$SRC_DIR/vendor/keys/claude-desktop.asc"
